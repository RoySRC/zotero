function field(row, name) {
  return row?.getResultByName ? row.getResultByName(name) : row?.[name];
}
async function createSQLiteStore({
  execute,
  now = Date.now,
  ttl = 864e5,
  maxEntries = 1e3,
  maxBytes = 64 * 1024 * 1024,
  revision = "projection-v2:"
}) {
  await execute(`CREATE TABLE IF NOT EXISTS metadata_cache (
		scope TEXT NOT NULL, public_key TEXT NOT NULL, record TEXT NOT NULL,
		expires_at INTEGER NOT NULL, updated_at INTEGER NOT NULL,
		PRIMARY KEY (scope, public_key))`);
  await execute("CREATE INDEX IF NOT EXISTS metadata_cache_expiry ON metadata_cache(expires_at)");
  let writes = Promise.resolve();
  return {
    /** Expired or malformed entries are misses, never permanent negative results. */
    async get(scope, key) {
      await writes;
      const rows = await execute(
        "SELECT record FROM metadata_cache WHERE scope=? AND public_key=? AND expires_at>?",
        [scope, revision + key, now()]
      );
      try {
        return rows.length ? JSON.parse(field(rows[0], "record")) : null;
      } catch {
        return null;
      }
    },
    /** Serialize writes and evictions. Failed writes do not poison the next operation. */
    put(scope, key, record) {
      const json = JSON.stringify(record);
      if (!record || new TextEncoder().encode(json).length > 256 * 1024) return Promise.resolve();
      const run = writes.then(async () => {
        const time = now();
        await execute("DELETE FROM metadata_cache WHERE expires_at<=?", [time]);
        await execute(
          `INSERT INTO metadata_cache VALUES (?,?,?,?,?) ON CONFLICT(scope, public_key)
					DO UPDATE SET record=excluded.record, expires_at=excluded.expires_at, updated_at=excluded.updated_at`,
          [scope, revision + key, json, time + ttl, time]
        );
        await execute(`DELETE FROM metadata_cache WHERE rowid IN (
					SELECT rowid FROM (SELECT rowid, ROW_NUMBER() OVER (ORDER BY updated_at DESC, rowid DESC) AS n,
					SUM(length(CAST(record AS BLOB))) OVER (ORDER BY updated_at DESC, rowid DESC) AS bytes FROM metadata_cache)
					WHERE n>? OR bytes>?)`, [maxEntries, maxBytes]);
      });
      writes = run.catch(() => {
      });
      return run;
    },
    /** Let shutdown wait for committed writes before closing the host connection. */
    async drain() {
      await writes;
    }
  };
}

