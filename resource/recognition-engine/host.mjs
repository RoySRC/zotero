function editionKey(value) {
  if (typeof value != "string") return null;
  const digits = value.replace(/[\s-]/g, "").toUpperCase();
  if (/^\d{9}[\dX]$/.test(digits)) {
    if ([...digits].reduce((sum, c, i) => sum + (c == "X" ? 10 : +c) * (10 - i), 0) % 11) return null;
    const prefix = "978" + digits.slice(0, 9);
    return prefix + (10 - [...prefix].reduce((sum, c, i) => sum + +c * (i % 2 ? 3 : 1), 0) % 10) % 10;
  }
  return /^97[89]\d{10}$/.test(digits) && [...digits].reduce((sum, c, i) => sum + +c * (i % 2 ? 3 : 1), 0) % 10 == 0 ? digits : null;
}

